# 95% confidence intervals for every accuracy number, plus the numbers for the limitations block
# - the unit is the QUESTION, not the repeat. at temperature 0 the 3 repeats of one question are
#   almost the same answer, so they are not independent samples. effective n = number of questions.
# - bootstrap CI: resample the questions (with replacement) 10,000 times, each question keeps all
#   of its repeats, take the 2.5% and 97.5% points of the mean accuracy. seed is fixed
# - wilson CI: on the per-question majority vote (passed in more than half of the repeats), n = questions
# - the lenient v0 re-score (logs/lenient/) is listed as its own row
# run: python eval/stats.py --split test   -> logs/accuracy_ci_<split>.csv and docs/limitations.md (test only)

import argparse
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import config
from significance import latest

B = 10000
SEED = 0


def wilson(k, n, z=1.96):
    if n == 0:
        return None, None
    p = k / n
    mid = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return round(100 * (mid - half), 1), round(100 * (mid + half), 1)


def boot(per_q, b=B, seed=SEED):
    # per_q = array with the mean pass rate of each question (over its repeats)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(per_q), size=(b, len(per_q)))
    means = per_q[idx].mean(axis=1) * 100
    return round(float(np.percentile(means, 2.5)), 1), round(float(np.percentile(means, 97.5)), 1)


def ci_row(g, label):
    g = g.assign(p=g["pass"].astype(str).str.lower() == "true")
    per_q = g.groupby("id")["p"].mean()
    rep = g.groupby("repeat")["p"].mean() * 100
    maj = int((per_q > 0.5).sum())
    lo, hi = boot(per_q.to_numpy())
    wlo, whi = wilson(maj, len(per_q))
    return {"version": label, "model": g["model"].iloc[0], "questions": len(per_q), "repeats": g["repeat"].nunique(),
            "accuracy": round(100 * g["p"].mean(), 1), "boot_lo": lo, "boot_hi": hi,
            "majority_acc": round(100 * maj / len(per_q), 1), "wilson_lo": wlo, "wilson_hi": whi,
            "repeat_min": round(rep.min(), 1), "repeat_max": round(rep.max(), 1),
            "unstable_questions": int(((per_q > 0) & (per_q < 1)).sum()), "run_id": g["run_id"].iloc[0]}


def read_all(folder):
    files = sorted(folder.glob("results_*.csv"))
    return pd.concat([pd.read_csv(f) for f in files], ignore_index=True) if files else pd.DataFrame()


def table(split):
    rows = []
    res = read_all(config.LOGS)
    for model in [config.MODEL] + sorted(set(res["model"]) - {config.MODEL}):
        d = latest(res, split, model)
        for v in sorted(d["version"].unique()):
            rows.append(ci_row(d[d["version"] == v], v))
    len_ = read_all(config.LOGS / "lenient")
    if len(len_):
        d = latest(len_, split, config.MODEL)
        for v in sorted(d["version"].unique()):
            rows.append(ci_row(d[d["version"] == v], f"{v} (lenient extractor)"))
    return pd.DataFrame(rows)


def limitations(t):
    main = t[(t["model"] == config.MODEL) & ~t["version"].str.contains("lenient")]
    ranges = "; ".join(f"{r.version} {r.repeat_min}–{r.repeat_max}%" for r in main.itertuples() if r.repeats > 1)
    unstable = "; ".join(f"{r.version} {r.unstable_questions} of {r.questions}" for r in main.itertuples() if r.repeats > 1)
    widest = main.assign(w=main["boot_hi"] - main["boot_lo"]).sort_values("w").iloc[-1] if len(main) else None
    n = int(main["questions"].max()) if len(main) else 0
    lines = [
        "# Limitations",
        "",
        "_Generated by `python eval/stats.py --split test` from the latest test results. Re-run it after new runs._",
        "",
        f"- **Small test set.** The held-out split has {n} questions, so one question is {100 / n:.1f} percentage points."
        if n else "- **Small test set.** Test split not run yet.",
    ]
    if widest is not None:
        lines.append(f"  95% bootstrap intervals are wide: the widest is {widest['version']} at "
                     f"{widest['boot_lo']}–{widest['boot_hi']}%. Differences smaller than that should not be read as real.")
    lines += [
        f"- **Repeats are not independent samples.** All runs use temperature 0, so the 3 repeats of a question "
        f"are nearly the same answer. Per-repeat accuracy ranges: {ranges or 'no repeated runs yet'}. "
        f"Questions whose result changed between repeats: {unstable or '-'}. The effective sample size is the "
        f"number of questions ({n}), not questions × repeats, so the confidence intervals and the McNemar test "
        "resample or pair by question.",
        "- **Gold queries are not verified.** All 60 gold queries were drafted with the help of Claude and are marked "
        "`verified: false` until a team member checks them. A wrong gold query moves every version's score.",
        "- **Business-rule assumptions.** \"Sales\" = delivered orders, and \"revenue\" = SUM(price) per product, "
        "category or seller. The v2–v4 prompts and the gold queries use the same definitions, which favours v2–v4 "
        "when a question is read another way. The team has not confirmed these yet.",
        "- **Error labels are drafts.** Failure categories were proposed by Claude from the SQL and need a human check.",
        "- **One database, English only.** Every question is about the Olist schema and is written in English. "
        "Nothing here says how the prompts work on other schemas or languages.",
        "- **One main model.** gpt-oss-120b on Groq, one setting. The gpt-oss-20b check is a single run.",
        "- **Prompt text changes more than one thing at a time.** v2 adds the CREATE TABLE text and the business rules "
        "together, so their separate effects are not measured.",
        "- **v4 shares v3's first answer.** v4 differs from v3 only by the repair loop, so v3 vs v4 measures repair alone.",
        "- **Execution accuracy can pass a wrong query** that happens to return the same rows as the gold query, "
        "and fails a correct query that formats a value differently (e.g. a percentage vs a fraction).",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test", choices=["dev", "test"])
    a = ap.parse_args()
    t = table(a.split)
    if t.empty:
        sys.exit(f"no results for the {a.split} split")
    path = config.LOGS / f"accuracy_ci_{a.split}.csv"
    t.to_csv(path, index=False)
    print(t.drop(columns=["run_id"]).to_string(index=False))
    print(f"\nsaved {path}")
    if a.split == "test":
        doc = ROOT / "docs" / "limitations.md"
        doc.write_text(limitations(t), encoding="utf-8")
        print(f"saved {doc}")


if __name__ == "__main__":
    main()
